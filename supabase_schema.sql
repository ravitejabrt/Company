-- 1. DROP EXISTING TABLES IF RE-INITIALIZING
DROP TABLE IF EXISTS rewards CASCADE;
DROP TABLE IF EXISTS collections CASCADE;
DROP TABLE IF EXISTS invoices CASCADE;
DROP TABLE IF EXISTS companies CASCADE;
DROP TABLE IF EXISTS agents CASCADE;
DROP TABLE IF EXISTS reward_tiers CASCADE;

-- 2. CREATE AGENTS TABLE
CREATE TABLE agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  phone TEXT,
  password TEXT DEFAULT 'agent123',
  badge_color TEXT DEFAULT '#3b82f6',
  status TEXT DEFAULT 'Active',
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. CREATE COMPANIES TABLE
CREATE TABLE companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  contact_person TEXT,
  contact_phone TEXT,
  category TEXT DEFAULT 'Enterprise',
  target_amount NUMERIC(12, 2) DEFAULT 0,
  agent_id BIGINT REFERENCES agents(id) ON DELETE SET NULL,
  status TEXT DEFAULT 'Pending',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. CREATE INVOICES TABLE (Prime User Issues Bills)
CREATE TABLE invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  invoice_number TEXT NOT NULL UNIQUE,
  invoice_date DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date DATE,
  amount NUMERIC(12, 2) NOT NULL,
  notes TEXT,
  created_by TEXT DEFAULT 'Prime User',
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. CREATE COLLECTIONS TABLE (Agents & Prime User Record Recoveries)
CREATE TABLE collections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  agent_id BIGINT REFERENCES agents(id) ON DELETE SET NULL,
  invoice_id BIGINT REFERENCES invoices(id) ON DELETE SET NULL,
  amount NUMERIC(12, 2) NOT NULL,
  payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
  payment_method TEXT DEFAULT 'Bank Transfer',
  reference_no TEXT,
  notes TEXT,
  recorded_by TEXT DEFAULT 'Prime User',
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 6. CREATE REWARDS TABLE (Prime User Grants Bonuses)
CREATE TABLE rewards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
  amount NUMERIC(12, 2) NOT NULL,
  reward_type TEXT DEFAULT 'Performance Bonus',
  reason TEXT,
  status TEXT DEFAULT 'Awarded',
  awarded_date DATE DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 7. CREATE REWARD TIERS TABLE
CREATE TABLE reward_tiers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tier_name TEXT NOT NULL,
  min_percentage NUMERIC(5, 2) NOT NULL,
  rate_percent NUMERIC(5, 2) NOT NULL,
  badge_name TEXT,
  description TEXT
);

-- ====================================================================
-- AUTOMATIC DATABASE FUNCTIONS & TRIGGERS
-- Keeps company target_amount and status automatically up-to-date
-- ====================================================================

-- Function to recalculate company target_amount from invoices and update status
CREATE OR REPLACE FUNCTION update_company_financials()
RETURNS TRIGGER AS $$
DECLARE
  target_comp_id BIGINT;
  new_target NUMERIC(12, 2);
  new_collected NUMERIC(12, 2);
  calc_status TEXT;
BEGIN
  target_comp_id := COALESCE(NEW.company_id, OLD.company_id);

  -- 1. Calculate sum of invoices
  SELECT COALESCE(SUM(amount), 0) INTO new_target
  FROM invoices
  WHERE company_id = target_comp_id;

  -- 2. Calculate sum of collections
  SELECT COALESCE(SUM(amount), 0) INTO new_collected
  FROM collections
  WHERE company_id = target_comp_id;

  -- 3. Determine status
  IF new_collected >= new_target AND new_target > 0 THEN
    calc_status := 'Completed';
  ELSIF new_collected > 0 THEN
    calc_status := 'In Progress';
  ELSE
    calc_status := 'Pending';
  END IF;

  -- 4. Update company record
  UPDATE companies
  SET target_amount = new_target,
      status = calc_status
  WHERE id = target_comp_id;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Trigger on invoices (INSERT, UPDATE, DELETE)
CREATE OR REPLACE TRIGGER trg_invoice_changes
AFTER INSERT OR UPDATE OR DELETE ON invoices
FOR EACH ROW EXECUTE FUNCTION update_company_financials();

-- Trigger on collections (INSERT, UPDATE, DELETE)
CREATE OR REPLACE TRIGGER trg_collection_changes
AFTER INSERT OR UPDATE OR DELETE ON collections
FOR EACH ROW EXECUTE FUNCTION update_company_financials();

